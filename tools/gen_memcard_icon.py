#!/usr/bin/env python3
"""Generate a PS2 memory card 3D icon (icon.icn) from a PNG image.

Turns an app-style square image into a textured two-sided flat card,
matching the format the PS2 browser/OSD renders (ps2icon format v0.5;
reference parser: caol64/ps2mc-browser packages/ps2mc-core/src/ps2mc/icon.py).

Binary layout (all little-endian):
  header  : u32 magic 0x00010000, u32 animation_shapes, u32 tex_type,
            u32 1.0f-pattern, u32 vertex_count
  vertices: per vertex, per shape: <3hH xyz; then <3hH normal,
            <2h uv, <4B rgba
  anim    : u32 magic 1, u32 frame_length, f32 anim_speed,
            u32 play_offset, u32 frame_count; per frame <4I
            (frame_data[1] = key count, then (keys-1) * <2f)
  texture : 128*128 u16 RGB5A1, present when tex_type & 4,
            RLE-compressed when tex_type & 8 (unused here)

Fixed-point factor for xyz / normals / uv is 4096 (i.e. 1.0 == 0x1000).
Vertices form a plain triangle list (every 3 vertices = 1 triangle).
"""
import struct
import sys

from PIL import Image

FIXED = 4096          # 1.0 in s16 fixed point
HALF = 6144           # card half size (~1.5) in fixed point
UVMAX = 0x1000        # uv 1.0
TEX_SIZE = 128 * 128 * 2
TEX_TYPE = 7          # bit2: texture present, no RLE compression
VERTEX_COUNT = 12     # 2 triangles per side x 2 sides


def build_texture(img_path):
    """Square-crop, resize to 128x128 and encode as RGB5A1 (opaque)."""
    im = Image.open(img_path).convert("RGBA")
    w, h = im.size
    s = min(w, h)
    im = im.crop(((w - s) // 2, (h - s) // 2, (w - s) // 2 + s, (h - s) // 2 + s))
    im = im.resize((128, 128), Image.LANCZOS).convert("RGBA")
    px = im.load()

    tex = bytearray(TEX_SIZE)
    for y in range(128):
        for x in range(128):
            r, g, b, a = px[x, y]
            if a < 128:
                # 1-bit alpha only: fill the rounded corners with the
                # icon's own white background instead of poking holes.
                r = g = b = 255
            r5, g5, b5 = r >> 3, g >> 3, b >> 3
            u16 = (1 << 15) | (b5 << 10) | (g5 << 5) | r5
            struct.pack_into("<H", tex, (y * 128 + x) * 2, u16)
    return bytes(tex), im


def build_geometry():
    """Two-sided flat card: front triangles with normal uv, back
    triangles with reversed winding and mirrored u (so the picture
    reads correctly from behind). All normals +z for even lighting."""
    tl, tr = (-HALF, -HALF), (HALF, -HALF)
    br, bl = (HALF, HALF), (-HALF, HALF)
    uv_tl, uv_tr = (0, 0), (UVMAX, 0)
    uv_br, uv_bl = (UVMAX, UVMAX), (0, UVMAX)
    mir = lambda uv: (UVMAX - uv[0], uv[1])

    tris = [
        (tl, uv_tl), (tr, uv_tr), (br, uv_br),   # front tri 1
        (tl, uv_tl), (br, uv_br), (bl, uv_bl),   # front tri 2
        (tr, mir(uv_tr)), (tl, mir(uv_tl)), (bl, mir(uv_bl)),  # back tri 1
        (tr, mir(uv_tr)), (bl, mir(uv_bl)), (br, mir(uv_br)),  # back tri 2
    ]

    out = bytearray()
    for (x, y), (u, v) in tris:
        out += struct.pack("<3hH", x, y, 0, 0x0400)          # xyz + w
        out += struct.pack("<3hH", 0, 0, FIXED, 0x0400)      # normal +z
        out += struct.pack("<2h", u, v)                      # uv
        out += bytes((0x80, 0x80, 0x80, 0x80))               # rgba
    return bytes(out)


def build_icon(png_path):
    tex, im = build_texture(png_path)
    geom = build_geometry()
    hdr = struct.pack("<5I", 0x00010000, 1, TEX_TYPE, 0x3F800000, VERTEX_COUNT)
    anim = struct.pack("<IIfII", 1, 100, 1.0, 0, 1)
    frame = struct.pack("<4I", 0, 1, 0, 0)
    return hdr + geom + anim + frame + tex, im


def verify(data):
    """Re-parse the generated bytes the way the reference parser does."""
    magic, shapes, tex_type, _one, count = struct.unpack_from("<5I", data, 0)
    assert magic == 0x00010000 and shapes == 1 and (tex_type & 4)
    off = 20
    for _ in range(count):
        off += 8 * shapes      # vertex coords
        off += 8 + 4 + 4       # normal + uv + rgba
    amagic, flen, speed, poff, fcount = struct.unpack_from("<IIfII", data, off)
    off += 20
    assert amagic == 1 and flen == 100 and speed == 1.0 and fcount == 1
    fd = struct.unpack_from("<4I", data, off)
    off += 16 + (fd[1] - 1) * 8
    assert len(data) - off == TEX_SIZE, (len(data) - off)
    return count


def to_inc(data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append(",".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print("usage: gen_memcard_icon.py <input.png> <output.inc>")
        sys.exit(1)
    data, im = build_icon(sys.argv[1])
    n = verify(data)
    with open(sys.argv[2], "w", newline="\n") as f:
        f.write(to_inc(data))
    prev = sys.argv[2] + ".preview.png"
    im.resize((256, 256), Image.BILINEAR).save(prev)
    print("icon.icn: %d bytes, %d vertices, texture 128x128 RGB5A1"
          % (len(data), n))
    print("preview : %s" % prev)
