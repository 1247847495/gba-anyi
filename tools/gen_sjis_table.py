#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成 UTF-8(Unicode) -> Shift-JIS 映射表 mc_sjis_table.inc。

PS2 浏览器(OSDSYS)的 icon.sys title 要求 Shift-JIS 编码，且 BIOS 字库
仅覆盖 JIS X 0208。本脚本遍历全部 Shift-JIS 双字节码位，只保留能用
iso2022_jp 表示(即 JIS X 0208 范围)的字符，生成按 Unicode 升序排列的
查表数组，供 memcard.cpp 二分查找。

另附"简体特有字 -> 日文汉字"别名表：PS2 字库无简体字形，将常用简体
独有字映射到同义的 JIS 汉字(如 拟->擬 汉->漢 戏->戲)。

用法: python3 tools/gen_sjis_table.py
输出: src/platform/ps2/memcard/mc_sjis_table.inc
"""

import os

OUT = os.path.join(os.path.dirname(__file__), "..",
                   "src", "platform", "ps2", "memcard", "mc_sjis_table.inc")

# 简体特有字 -> JIS X 0208 中存在的同义日文/繁体字形
# (仅收录常用字；未收录的简体字将显示为全角 '?')
SIMPLIFIED_ALIAS = {
    "拟": "擬", "汉": "漢", "戏": "戲", "机": "機", "软": "軟",
    "读": "讀", "写": "寫", "设": "設", "开": "開", "关": "關",
    "选": "選", "单": "單", "语": "語", "别": "別", "称": "稱",
    "红": "紅", "蓝": "藍", "绿": "緑", "车": "車", "载": "載",
    "复": "複", "贴": "貼", "动": "動", "联": "連", "视": "視",
    "频": "頻", "乐": "樂", "态": "態", "时": "時", "间": "間",
    "钟": "鐘", "标": "標", "传": "傳", "输": "輸", "无": "無",
    "请": "請", "见": "見", "记": "記", "忆": "憶", "风": "風",
    "云": "雲", "电": "電", "灯": "燈", "简": "簡", "优": "優",
    "转": "轉", "换": "換", "图": "圖", "应": "應", "启": "啓",
    "确": "確", "认": "認", "环": "環", "统": "統", "稳": "穩",
    "测": "測", "试": "試", "级": "級", "毕": "畢", "变": "變",
    "码": "碼", "维": "維", "护": "護", "览": "覽", "缩": "縮",
    "扩": "擴", "执": "執", "续": "續", "误": "誤", "备": "備",
    "镜": "鏡", "头": "頭", "说": "説", "录": "録", "压": "壓",
    "补": "補", "锁": "鎖", "帧": "幀", "墙": "牆",
}


def build_table():
    # 1) 遍历 Shift-JIS 双字节码位 -> Unicode
    uni2sjis = {}
    for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xF0)):
        for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFC)):
            raw = bytes([lead, trail])
            try:
                ch = raw.decode("cp932")
                # 仅保留 JIS X 0208 内字符(PS2 BIOS 字库范围)
                ch.encode("iso2022_jp")
            except (UnicodeDecodeError, UnicodeEncodeError):
                continue
            cp = ord(ch)
            if cp < 0x80 or cp in uni2sjis:
                continue
            uni2sjis[cp] = (lead << 8) | trail

    # 2) 叠加简体别名(简体码点 -> 日文字形的 SJIS)
    missing = []
    for simp, trad in SIMPLIFIED_ALIAS.items():
        sj = uni2sjis.get(ord(trad))
        if sj is None:
            missing.append((simp, trad))
            continue
        uni2sjis[ord(simp)] = sj   # 同码点覆盖: 简体查到日文字形
    if missing:
        print("WARN: alias target not in JIS X 0208:",
              ", ".join(f"{a}->{b}" for a, b in missing))

    return sorted(uni2sjis.items())


def main():
    table = build_table()
    lines = []
    lines.append("/* Auto-generated by tools/gen_sjis_table.py - DO NOT EDIT")
    lines.append(" * Unicode -> Shift-JIS (JIS X 0208 subset, PS2 OSDSYS")
    lines.append(" * icon.sys title compatible). Sorted by Unicode for")
    lines.append(" * binary search. Includes simplified-Chinese aliases")
    lines.append(" * mapped to equivalent JIS kanji (e.g. U+62DF 拟 -> 擬).")
    lines.append(" * Entries: %d */" % len(table))
    lines.append("#define MC_SJIS_TABLE_SIZE %d" % len(table))
    lines.append("static const unsigned short _McSjisTable"
                 "[MC_SJIS_TABLE_SIZE][2] = {")
    for i in range(0, len(table), 4):
        row = table[i:i + 4]
        lines.append("\t" + " ".join("{0x%04X,0x%04X}," % e for e in row))
    lines.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d entries)" % (os.path.normpath(OUT), len(table)))


if __name__ == "__main__":
    main()
